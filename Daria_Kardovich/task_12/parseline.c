#include <ctype.h>
#include <stdio.h>
#include <string.h>

#include "shell.h"

static char *blankskip(char *s) // Пропускает пробелы и возвращает указатель на первый непробельный символ
{
    while (*s && isspace((unsigned char)*s)) {
        s++; // Передвигаем указатель на следующий символ
    }

    return s; // Возвращаем указатель на первый непробельный символ
}

int parseline(char *line) // Разбирает введённую строку на команды аргументы и специальные символы
{
    int nargs; // Количество аргументов текущей команды
    int ncmds; // Номер текущей команды
    int rval; // Количество найденных команд которое вернёт функция
    int i; // Счётчик для цикла очистки массива команд
    char aflg = 0; // Флаг символов >> для дописывания в файл
    char *s = line; // Указатель на текущий символ разбираемой строки
    static char delim[] = " \t|&<>;\n"; // Символы которые разделяют слова и команды

    bkgrnd = 0; // Сбрасываем флаг фонового режима
    nargs = 0; // В текущей команде пока нет аргументов
    ncmds = 0; // Начинаем с первой команды
    rval = 0; // Пока не найдено ни одной команды

    infile = NULL; // Сбрасываем имя входного файла
    outfile = NULL; // Сбрасываем имя выходного файла
    appfile = NULL; // Сбрасываем имя файла для дописывания

    for (i = 0; i < MAXCMDS; i++) { // Проходим по всему массиву команд
        cmds[i].cmdflag = 0; // Сбрасываем флаги каналов у команды
        cmds[i].cmdargs[0] = NULL; // Говорим что у команды пока нет аргументов
    }

    while (*s) { // Работаем пока не дошли до конца введённой строки
        s = blankskip(s); // Пропускаем пробелы перед следующим словом или символом

        if (!*s) { // Проверяем не закончилась ли строка после пробелов
            break; // Выходим из цикла разбора
        }

        switch (*s) { // Проверяем какой специальный символ или обычное слово найдено
            case '&': // Обрабатываем символ фонового режима
                bkgrnd = 1; // Запоминаем что команда должна работать в фоне
                *s++ = '\0'; // Заменяем символ & на конец строки и передвигаем указатель
                break; // Завершаем обработку символа &
            
            case '>': // Обрабатываем перенаправление вывода в файл
                if (*(s + 1) == '>') { // Проверяем есть ли второй символ >
                    aflg = 1; // Запоминаем что нужно дописывать в файл
                    *s++ = '\0'; // Убираем первый символ > из строки
                }

                *s++ = '\0'; // Убираем второй символ > или единственный символ >
                s = blankskip(s); // Пропускаем пробелы перед именем файла

                if (!*s) { // Проверяем указано ли имя файла
                    fprintf(stderr, "syntax error\n"); // Печатаем ошибку синтаксиса
                    return -1; // Возвращаем ошибку
                }

                if (aflg) { // Проверяем был ли символ >>
                    appfile = s; // Сохраняем имя файла для дописывания
                } else {
                    outfile = s; // Сохраняем имя файла для перезаписи
                }

                s = strpbrk(s, delim); // Ищем следующий специальный символ или пробел после имени файла

                if (s != NULL && isspace((unsigned char)*s)) { // Проверяем что найден пробел
                    *s++ = '\0'; // Заменяем пробел концом строки и передвигаем указатель
                }

                break; // Завершаем обработку символа >

            case '<': // Обрабатываем перенаправление ввода из файла
                *s++ = '\0'; // Убираем символ < из строки и передвигаем указатель
                s = blankskip(s); // Пропускаем пробелы перед именем файла

                if (!*s) { // Проверяем указано ли имя входного файла
                    fprintf(stderr, "syntax error\n"); // Печатаем ошибку синтаксиса
                    return -1; // Возвращаем ошибку
                }

                infile = s; // Сохраняем указатель на имя входного файла
                s = strpbrk(s, delim); // Ищем следующий разделитель после имени файла

                if (s != NULL && isspace((unsigned char)*s)) { // Проверяем что найден пробел
                    *s++ = '\0'; // Заменяем пробел концом строки и передвигаем указатель
                }

                break; // Завершаем обработку символа <

            case '|': // Обрабатываем символ программного канала
                if (nargs == 0) { // Проверяем есть ли команда слева от символа |
                    fprintf(stderr, "syntax error\n"); // Печатаем ошибку синтаксиса
                    return -1; // Возвращаем ошибку
                }

                cmds[ncmds++].cmdflag |= OUTPIP; // Помечаем что вывод текущей команды идёт в канал
                cmds[ncmds].cmdflag |= INPIP; // Помечаем что следующая команда получает ввод из канала
                *s++ = '\0'; // Убираем символ | из строки и передвигаем указатель
                nargs = 0; // У следующей команды пока нет аргументов
                break; // Завершаем обработку символа |

            case ';': // Обрабатываем символ разделения независимых команд
                *s++ = '\0'; // Убираем символ ; из строки и передвигаем указатель
                ncmds++; // Переходим к следующей команде
                nargs = 0; // У новой команды пока нет аргументов
                break; // Завершаем обработку символа ;

            default: // Обрабатываем обычное слово команды или аргумент
                if (nargs == 0) { // Проверяем является ли слово первым в новой команде
                    rval = ncmds + 1; // Обновляем количество найденных команд
                }

                cmds[ncmds].cmdargs[nargs++] = s; // Сохраняем указатель на слово в массив аргументов
                cmds[ncmds].cmdargs[nargs] = NULL; // Добавляем NULL после последнего аргумента
                s = strpbrk(s, delim); // Ищем следующий разделитель после слова

                if (s != NULL && isspace((unsigned char)*s)) { // Проверяем что найден пробел
                    *s++ = '\0'; // Заменяем пробел концом строки и передвигаем указатель
                }

                break; // Завершаем обработку обычного слова
        }
    }

    if (ncmds > 0 && nargs == 0 && // Проверяем что после символа | не написали вторую команду
        (cmds[ncmds - 1].cmdflag & OUTPIP)) {
        fprintf(stderr, "syntax error\n"); // Печатаем ошибку синтаксиса
        return -1; // Возвращаем ошибку
    }

    return rval; // Возвращаем количество разобранных команд
}
